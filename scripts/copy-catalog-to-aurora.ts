import { Signer } from "@aws-sdk/rds-signer";
import Database from "better-sqlite3";
import pg from "pg";

const host =
  process.env.AURORA_HOST ??
  "renderz.cluster-cv4068ogwct9.ap-southeast-1.rds.amazonaws.com";
const region = process.env.AWS_REGION ?? "ap-southeast-1";
const user = process.env.AURORA_USER ?? "postgres";
const database = process.env.AURORA_DATABASE ?? "postgres";
const port = Number(process.env.AURORA_PORT ?? 5432);
const sqlitePath = process.env.SQLITE_PATH ?? "data/catalog.sqlite";

const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS players (
  id text PRIMARY KEY,
  slug text NOT NULL DEFAULT '',
  name text NOT NULL,
  rating integer NOT NULL,
  first_name text,
  last_name text,
  common_name text,
  card_name text,
  position text,
  alt_positions jsonb NOT NULL DEFAULT '[]'::jsonb,
  program_id text,
  program_name text,
  club_name text,
  nation_name text,
  league_name text,
  auctionable boolean,
  foot text,
  weak_foot text,
  skill_moves_level text,
  height_cm integer,
  weight_kg integer,
  work_rate_att text,
  work_rate_def text,
  birthday text,
  stats jsonb NOT NULL DEFAULT '[]'::jsonb,
  total_stats integer,
  meta_rating double precision,
  traits jsonb NOT NULL DEFAULT '[]'::jsonb,
  play_styles jsonb NOT NULL DEFAULT '[]'::jsonb,
  skills jsonb NOT NULL DEFAULT '[]'::jsonb,
  related_card_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  star_signings_buy integer,
  star_signings_sell integer,
  available_image_kinds jsonb NOT NULL DEFAULT '[]'::jsonb,
  added_at bigint,
  fetched_at bigint NOT NULL,
  parse_version integer NOT NULL,
  discovered_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS player_assets (
  player_id text NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  kind text NOT NULL,
  upstream_url text NOT NULL,
  fetched_at bigint NOT NULL,
  PRIMARY KEY (player_id, kind)
);

CREATE TABLE IF NOT EXISTS ingest_jobs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id text NOT NULL,
  slug text,
  kind text NOT NULL,
  status text NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  last_error text,
  claimed_at bigint,
  completed_at bigint,
  next_attempt_at bigint NOT NULL,
  created_at bigint NOT NULL
);
`;

type PlayerRow = Record<string, unknown>;

function jsonValue(value: unknown): string {
  if (typeof value === "string") {
    return value.length > 0 ? value : "[]";
  }
  return JSON.stringify(value ?? []);
}

function boolValue(value: unknown): boolean | null {
  if (value === null || value === undefined) {
    return null;
  }
  return Number(value) !== 0;
}

async function connect(): Promise<pg.Client> {
  const signer = new Signer({ hostname: host, port, username: user, region });
  const client = new pg.Client({
    host,
    port,
    user,
    database,
    password: await signer.getAuthToken(),
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 60_000,
  });
  await client.connect();
  return client;
}

function valueGroup(width: number, offset: number, casts: Array<string | undefined>): string {
  const items = Array.from({ length: width }, (_, index) => {
    const placeholder = `$${offset + index + 1}`;
    const cast = casts[index];
    return cast ? `${placeholder}::${cast}` : placeholder;
  });
  return `(${items.join(", ")})`;
}

async function insertBatches(
  client: pg.Client,
  sqlPrefix: string,
  rows: unknown[][],
  casts: Array<string | undefined> = [],
): Promise<void> {
  const width = rows[0]?.length ?? 0;
  const batchSize = 200;
  for (let start = 0; start < rows.length; start += batchSize) {
    const batch = rows.slice(start, start + batchSize);
    const values: unknown[] = [];
    const groups = batch.map((row, rowIndex) => {
      values.push(...row);
      return valueGroup(width, rowIndex * width, casts);
    });
    await client.query(`${sqlPrefix} VALUES ${groups.join(", ")}`, values);
  }
}

async function main() {
  const sqlite = new Database(sqlitePath, { readonly: true, fileMustExist: true });
  const client = await connect();
  console.log(`connected ${host}/${database}`);

  try {
    await client.query("BEGIN");
    await client.query(SCHEMA_SQL);
    await client.query(
      "TRUNCATE TABLE ingest_jobs, player_assets, players RESTART IDENTITY CASCADE",
    );

    const players = sqlite.prepare("SELECT * FROM players").all() as PlayerRow[];
    await insertBatches(
      client,
      `INSERT INTO players (
        id, slug, name, rating, first_name, last_name, common_name, card_name, position,
        alt_positions, program_id, program_name, club_name, nation_name, league_name,
        auctionable, foot, weak_foot, skill_moves_level, height_cm, weight_kg,
        work_rate_att, work_rate_def, birthday, stats, total_stats, meta_rating, traits,
        play_styles, skills, related_card_ids, star_signings_buy, star_signings_sell,
        available_image_kinds, added_at, fetched_at, parse_version, discovered_at
      )`,
      players.map((row) => [
        row.id,
        row.slug,
        row.name,
        row.rating,
        row.first_name,
        row.last_name,
        row.common_name,
        row.card_name,
        row.position,
        jsonValue(row.alt_positions),
        row.program_id,
        row.program_name,
        row.club_name,
        row.nation_name,
        row.league_name,
        boolValue(row.auctionable),
        row.foot,
        row.weak_foot,
        row.skill_moves_level,
        row.height_cm,
        row.weight_kg,
        row.work_rate_att,
        row.work_rate_def,
        row.birthday,
        jsonValue(row.stats),
        row.total_stats,
        row.meta_rating,
        jsonValue(row.traits),
        jsonValue(row.play_styles),
        jsonValue(row.skills),
        jsonValue(row.related_card_ids),
        row.star_signings_buy,
        row.star_signings_sell,
        jsonValue(row.available_image_kinds),
        row.added_at,
        row.fetched_at,
        row.parse_version,
        row.discovered_at,
      ]),
      [
        undefined, undefined, undefined, undefined, undefined, undefined, undefined, undefined, undefined,
        "jsonb",
        undefined, undefined, undefined, undefined, undefined, undefined, undefined, undefined, undefined,
        undefined, undefined, undefined, undefined, undefined,
        "jsonb",
        undefined, undefined,
        "jsonb", "jsonb", "jsonb", "jsonb",
        undefined, undefined,
        "jsonb",
      ],
    );
    console.log(`players ${players.length}`);

    const assets = sqlite
      .prepare("SELECT player_id, kind, upstream_url, fetched_at FROM player_assets")
      .all() as PlayerRow[];
    await insertBatches(
      client,
      "INSERT INTO player_assets (player_id, kind, upstream_url, fetched_at)",
      assets.map((row) => [row.player_id, row.kind, row.upstream_url, row.fetched_at]),
    );
    console.log(`player_assets ${assets.length}`);

    const jobs = sqlite
      .prepare(
        `SELECT id, player_id, slug, kind, status, attempts, last_error, claimed_at,
                completed_at, next_attempt_at, created_at
         FROM ingest_jobs`,
      )
      .all() as PlayerRow[];
    await insertBatches(
      client,
      `INSERT INTO ingest_jobs (
        id, player_id, slug, kind, status, attempts, last_error, claimed_at,
        completed_at, next_attempt_at, created_at
      )`,
      jobs.map((row) => [
        row.id,
        row.player_id,
        row.slug,
        row.kind,
        row.status,
        row.attempts,
        row.last_error,
        row.claimed_at,
        row.completed_at,
        row.next_attempt_at,
        row.created_at,
      ]),
    );
    await client.query(
      "SELECT setval(pg_get_serial_sequence('ingest_jobs', 'id'), COALESCE((SELECT MAX(id) FROM ingest_jobs), 1))",
    );
    console.log(`ingest_jobs ${jobs.length}`);

    await client.query("COMMIT");

    const counts = await client.query(
      `SELECT 'players' AS table_name, COUNT(*)::int AS n FROM players
       UNION ALL SELECT 'player_assets', COUNT(*)::int FROM player_assets
       UNION ALL SELECT 'ingest_jobs', COUNT(*)::int FROM ingest_jobs`,
    );
    for (const row of counts.rows) {
      console.log(`aurora ${row.table_name}=${row.n}`);
    }
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    sqlite.close();
    await client.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
